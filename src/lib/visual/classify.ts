export interface Classification {
  theme: Theme | null;
  form: Form | null;
  /** テーマカラーの系統（テーマ → 形 → 一般の順） */
  genre: Genre;
}

/** 判定に使うテキスト（商品名・シリーズ・キャラクター・タグ） */
function classifyText(product: Pick<CatalogProduct, "name" | "series" | "tags" | "characters">): string {
  return normalizeForSearch([product.name, product.series, ...product.characters, ...product.tags].join(" "));
}

export function classifyProduct(product: Pick<CatalogProduct, "name" | "series" | "tags" | "characters">): Classification {
  const text = classifyText(product);
  const theme = THEME_RULES.find(([, rx]) => rx.test(text))?.[0] ?? null;
  const form = FORM_RULES.find(([, rx]) => rx.test(text))?.[0] ?? null;
  return { theme, form, genre: theme ?? form ?? "general" };
}

/** シリーズの識別に使わない一般的なタグ・語 */
const GENERIC = new Set(
  [
    "新商品",
    "オリジナル",
    "キャラクター",
    "その他のキャラクター",
    "アーティスト",
    "再販",
    "ガシャポン",
    "フラットガシャポン",
    "プレミアムガシャポン",
    "カプセルトイ",
    "コロコロコレクション",
  ].map(normalizeForSearch),
);

/**
 * シリーズの識別子（同じシリーズの商品は同じテーマカラー・同じ背景パターンになる）。
 * シリーズ名があればそれを使い、無ければ商品名の先頭の語（「ちいかわ ふわふわマスコット」なら「ちいかわ」）を使う。
 */
export function seriesKeyOf(product: Pick<CatalogProduct, "name" | "series" | "maker">): string {
  const series = normalizeForSearch(product.series ?? "");
  if (series && !GENERIC.has(series)) return `${product.maker}|${series}`;
  const name = (product.name ?? "")
    .normalize("NFKC")
    .replace(/^\s*[【[（(][^】\]）)]*[】\]）)]\s*/g, "") // 先頭の【再販】などの区分
    .replace(/^[\s“"”'『「]+/, "");
  // 先頭の語（「コロコロコレクション」のような一般的な語は飛ばす）
  const first = name.split(/[\s　”"』」]+/).find((w) => w.length > 0 && !GENERIC.has(normalizeForSearch(w))) ?? "";
  // 空白の無い長い商品名は先頭の数文字で代用する
  const token = first.length > 12 ? first.slice(0, 6) : first;
  return `${product.maker}|${normalizeForSearch(token)}`;
}
